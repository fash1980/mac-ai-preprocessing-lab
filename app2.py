@st.cache_resource
def client(url: str, key: str):
    from supabase import create_client
    return create_client(url, key)


def get_db():
    try:
        url = st.secrets["SUPABASE_URL"]
        key = st.secrets["SUPABASE_SERVICE_ROLE_KEY"]
        if url and key:
            return client(url, key)
    except (KeyError, FileNotFoundError):
        return None
    except Exception:
        st.error("Could not connect to the submissions database. Contact your tutor.")
    return None


db = get_db()
if db is None:
    st.warning("Database not configured. Do not share with students yet; submissions cannot be saved.")
if typing_input is None:
    st.error("Missing typing_input/index.html. Restore this file in your GitHub repository.")

